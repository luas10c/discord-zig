pub fn Payload(comptime t: Type) type {
    return switch (t) {
        .message_create, .message_update => schema.Message,
        .message_delete => MessageDelete,
        .guild_member_add, .guild_member_update => schema.GuildMember,
        .guild_member_remove => GuildMemberRemove,
        .guild_members_chunk => schema.GuildMembersChunk,
        .message_reaction_add, .message_reaction_remove => schema.MessageReaction,
        .message_reaction_remove_all => schema.ReactionRemoveAll,
        .message_reaction_remove_emoji => schema.ReactionRemoveEmoji,
        .guild_ban_add, .guild_ban_remove => schema.GuildBan,
        .guild_role_create, .guild_role_update => schema.Role,
        .guild_role_delete => RoleDelete,
        .typing_start => schema.TypingStart,
        .presence_update => schema.Presence,
        .voice_state_update => schema.VoiceState,
        .voice_server_update => schema.VoiceServerUpdate,
        .webhooks_update => schema.WebhooksUpdate,
        .ready => schema.Ready,
        .resumed => void,
        .channel_create, .channel_update, .channel_delete => schema.Channel,
        .interaction_create => schema.Interaction,
        .message_poll_vote_add, .message_poll_vote_remove => schema.MessagePollVote,
        .entitlement_create, .entitlement_update, .entitlement_delete => schema.Entitlement,
        else => std.json.Value,
    };
}

