pub fn normalize(comptime ev: anytype) Type {
    if (@TypeOf(ev) == Type) return ev;
    if (@TypeOf(ev) == Events) return fromEvents(ev);
    if (@typeInfo(@TypeOf(ev)) == .enum_literal) {
        const t: Type = ev;
        return t;
    }
    const name: []const u8 = ev;
    return @field(Names{}, name);
}

